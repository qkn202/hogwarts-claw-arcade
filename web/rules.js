export const clamp = (n, min, max) => Math.max(min, Math.min(max, n))
export const ease = t => { t = clamp(t, 0, 1); return t * t * (3 - 2 * t) }
export const lerp = (a, b, t) => a + (b - a) * t
// One transparent rule: a centred, reachable toy is caught. No payout cycle or forced misses.
export function findCatch(toys, x) {
  let candidate = null, distance = Infinity
  for (const toy of toys) {
    if (toy.state !== 'free') continue
    const dx = Math.abs(toy.x - x)
    if (dx <= toy.radius * 0.92 && dx < distance) { candidate = toy; distance = dx }
  }
  return candidate
}
export function inPrizeChute(x) { return x > .72 && x < 1.18 }
export function loadCollection(storage) {
  const clean = { bear: 0, rabbit: 0, cat: 0 }
  try {
    const saved = JSON.parse(storage.getItem('momo-claw.collection.v1') || '{}')
    for (const key of Object.keys(TYPES)) {
      if (Number.isSafeInteger(saved[key]) && saved[key] >= 0) {
        if (key in clean || saved[key] > 0) clean[key] = saved[key]
      }
    }
  } catch { /* Collection is optional: keep playing when storage is unavailable. */ }
  return clean
}
export function saveCollection(storage, collection) {
  try { storage.setItem('momo-claw.collection.v1', JSON.stringify(collection)) } catch { /* session still works */ }
}
